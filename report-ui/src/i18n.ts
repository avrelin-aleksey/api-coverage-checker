export function methodLabel(method: string): string {
  return String(method || "").replace(/^HTTPMethod\./, "").toUpperCase();
}

export function stateLabel(lang: Lang, state: string): string {
  if (state === "seen") return I18N[lang].seen;
  if (state === "absent") return I18N[lang].absent;
  if (state === "unused") return I18N[lang].unused;
  return state;
}

export function stateHint(lang: Lang, state: string): string {
  if (state === "seen") return I18N[lang].seenHint;
  if (state === "absent") return I18N[lang].absentHint;
  if (state === "unused") return I18N[lang].unusedHint;
  return "";
}
